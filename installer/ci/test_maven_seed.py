import json
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

import maven_seed as seed


IDENTITY = {'maven': '3.9.9', 'java': '21, vendor: Eclipse Adoptium', 'node': '22.16.0',
            'os': 'Linux', 'architecture': 'x86_64'}


class MavenSeedTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.project = self.root / 'project'
        self.project.mkdir()
        subprocess.run(['git', 'init', '-q', str(self.project)], check=True)
        self.put(self.project / 'pom.xml', '<project/>')
        self.put(self.project / 'src/main/java/App.java', 'tracked original')
        self.put(self.project / 'src/main/java/Deleted.java', 'delete me')
        subprocess.run(['git', '-C', str(self.project), 'add', '.'], check=True)
        self.put(self.project / 'src/main/java/App.java', 'dirty bytes')
        (self.project / 'src/main/java/Deleted.java').unlink()
        self.put(self.project / 'src/test/java/Untracked.java', 'new test')
        self.put(self.project / 'Dockerfile.release', 'FROM scratch')
        self.put(self.project / 'Dockerfile.release.dockerignore', '**\n!target/*.jar\n')
        self.put(self.project / 'installer/ci/__pycache__/stale.cpython-314.pyc', 'generated bytecode')
        self.put(self.project / 'installer/ci/orphan.pyc', 'generated bytecode')
        subprocess.run(['git', '-C', str(self.project), 'add', '-f',
                        'installer/ci/__pycache__/stale.cpython-314.pyc',
                        'installer/ci/orphan.pyc'], check=True)
        for relative in ('output/token.txt', 'installer/bundles/private.jar', '.m2/settings.xml',
                         'installer/private.env', 'installer/private.key', 'notes-credentials.txt'):
            self.put(self.project / relative, 'private credential fixture')
        self.put(self.project / 'installer/bundles/RELEASE-BOM.env', 'BOM_RELEASE=test\n')
        subprocess.run(['git', '-C', str(self.project), 'add', '-f',
                        'installer/bundles/RELEASE-BOM.env'], check=True)
        self.cache = self.root / '.m2/repository'
        self.artifact = self.cache / 'org/demo/demo/1.0/demo-1.0.jar'
        self.put(self.artifact, 'candidate artifact')
        for relative in ('settings.xml', 'org/demo/demo/1.0/demo-1.0.credentials',
                         'org/demo/demo/1.0/demo-1.0.jar.lastUpdated', 'org/demo/demo/1.0/_remote.repositories'):
            self.put(self.cache / relative, 'must not export')
        self.output = self.root / 'seed'

    def tearDown(self):
        self.tmp.cleanup()

    def put(self, path, data):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(data, encoding='utf-8')

    def test_identity_requires_and_pins_node_for_ui_tests(self):
        maven = subprocess.CompletedProcess([], 0, 'Apache Maven 3.9.9\nJava version: 21, vendor: Eclipse Adoptium\n')
        node = subprocess.CompletedProcess([], 0, 'v22.16.0\n')
        expected = {**IDENTITY, 'os': seed.platform.system(), 'architecture': seed.platform.machine()}
        with (patch.object(seed.shutil, 'which', return_value='/usr/bin/node'),
              patch.object(seed.subprocess, 'run', side_effect=[maven, node])):
            self.assertEqual(expected, seed.maven_identity('mvn'))

        with (patch.object(seed.shutil, 'which', return_value=None),
              patch.object(seed.subprocess, 'run', return_value=maven)):
            with self.assertRaisesRegex(seed.SeedError, 'Node.js is required'):
                seed.maven_identity('mvn')

    def collect(self):
        with patch.object(seed, 'maven_identity', return_value=IDENTITY):
            seed.collect([f'deploy-system={self.project}', f'worksystem-server={self.project}'],
                         [str(self.cache)], 'mvn', self.output, 'Windows')

    def test_current_worktree_filtered_cache_and_identity(self):
        before = seed.digest(self.artifact)
        self.collect()
        lock = seed.verify_seed(self.output)
        self.assertEqual('Windows', lock['cache_origin'])
        self.assertEqual(IDENTITY, lock['identity'])
        files = {item['path'] for item in lock['files']}
        self.assertEqual('dirty bytes', (self.output / 'sources/deploy-system/src/main/java/App.java').read_text())
        self.assertIn('sources/deploy-system/src/test/java/Untracked.java', files)
        self.assertIn('sources/deploy-system/Dockerfile.release', files)
        self.assertIn('sources/deploy-system/Dockerfile.release.dockerignore', files)
        self.assertIn('sources/deploy-system/installer/bundles/RELEASE-BOM.env', files)
        self.assertFalse(any('__pycache__' in path or path.endswith(('.pyc', '.pyo')) for path in files))
        self.assertFalse(any(path.endswith('installer/bundles/private.jar') for path in files))
        self.assertFalse(any('Deleted' in path or 'private' in path or 'credentials' in path for path in files))
        self.assertFalse(any('settings.xml' in path or 'lastUpdated' in path or '_remote.repositories' in path for path in files))
        self.assertEqual(before, seed.digest(self.artifact))

    def test_missing_tampered_extra_and_lock_pin(self):
        self.collect()
        fingerprint = seed.digest(self.output / 'seed.lock.json')
        artifact = self.output / 'repository/org/demo/demo/1.0/demo-1.0.jar'
        artifact.unlink()
        with self.assertRaises(seed.SeedError):
            seed.verify_seed(self.output)
        self.put(artifact, 'tampered')
        with self.assertRaises(seed.SeedError):
            seed.verify_seed(self.output)
        self.put(artifact, 'candidate artifact')
        self.put(self.output / 'extra.txt', 'extra')
        with self.assertRaises(seed.SeedError):
            seed.verify_seed(self.output)
        (self.output / 'extra.txt').unlink()
        lock_file = self.output / 'seed.lock.json'
        lock_file.write_text(lock_file.read_text() + ' ')
        with self.assertRaises(seed.SeedError):
            seed.verify_seed(self.output, fingerprint)

    def test_unsafe_paths_and_symlink(self):
        for path in ('../escape', '/absolute', 'a/../../x', 'a\\b', 'C:/x', 'a//b'):
            with self.assertRaises(seed.SeedError):
                seed.safe_path(path)
        self.collect()
        try:
            (self.output / 'link').symlink_to(self.artifact)
        except OSError as error:
            self.skipTest(f'Host cannot create symlinks: {error}')
        with self.assertRaises(seed.SeedError):
            seed.verify_seed(self.output)

    def test_absent_failed_skipped_tests_are_failure(self):
        report = self.root / 'reports/target/surefire-reports/TEST-example.xml'
        for attributes in ('tests="0"', 'tests="1" failures="1"', 'tests="1" skipped="1"', 'tests="1" errors="1"'):
            self.put(report, f'<testsuite {attributes}/>')
            with self.assertRaises(seed.SeedError):
                seed.test_evidence(self.root / 'reports')

    def test_build_calls_offline_clean_verify_in_private_work_without_skip(self):
        self.collect()
        work = self.root / 'build'
        calls = []

        def simulated_maven(command, **kwargs):
            calls.append(command)
            project = Path(kwargs['cwd'])
            self.put(project / 'target/surefire-reports/TEST-example.xml', '<testsuite tests="2" failures="0" errors="0" skipped="0"/>')
            self.put(project / 'target/example.jar', 'test fixture output, not a real Java build')
            return subprocess.CompletedProcess(command, 0)

        with patch.object(seed, 'maven_identity', return_value=IDENTITY), patch.object(seed.subprocess, 'run', side_effect=simulated_maven):
            result = seed.verify_build(self.output, 'mvn', work, seed.digest(self.output / 'seed.lock.json'))
        self.assertTrue(result['passed'])
        self.assertEqual(2, len(calls))
        for command in calls:
            self.assertEqual(['clean', 'verify'], command[-2:])
            self.assertIn('--offline', command)
            self.assertIn('--settings', command)
            self.assertIn('--global-settings', command)
            self.assertFalse(any('skip' in value.lower() for value in command))
            self.assertTrue(any(str(work) in value and 'maven.repo.local=' in value for value in command))
        self.assertFalse((self.project / 'target').exists())
        self.assertTrue((work / 'verification.json').is_file())

    def test_build_failure_cannot_attest_success(self):
        self.collect()
        work = self.root / 'failed-build'
        with patch.object(seed, 'maven_identity', return_value=IDENTITY), patch.object(seed.subprocess, 'run', return_value=subprocess.CompletedProcess([], 1)):
            with self.assertRaises(seed.SeedError):
                seed.verify_build(self.output, 'mvn', work, seed.digest(self.output / 'seed.lock.json'))
        self.assertFalse(json.loads((work / 'verification.json').read_text())['passed'])

    def test_existing_output_and_work_are_never_overwritten(self):
        self.collect()
        with self.assertRaises(seed.SeedError):
            self.collect()
        work = self.root / 'existing'
        self.put(work / 'keep.txt', 'user data')
        with patch.object(seed, 'maven_identity', return_value=IDENTITY):
            with self.assertRaises(seed.SeedError):
                seed.verify_build(self.output, 'mvn', work, seed.digest(self.output / 'seed.lock.json'))
        self.assertEqual('user data', (work / 'keep.txt').read_text())

    def test_runtime_literal_credential_requires_review(self):
        self.put(self.project / 'src/main/resources/application.yml', 'password: do-not-copy-this-literal\n')
        with self.assertRaises(seed.SeedError):
            self.collect()

    def test_release_bom_rejects_secret_like_content(self):
        bom = self.project / 'installer/bundles/RELEASE-BOM.env'
        cases = (
            ('BOM_RELEASE=2026.10\nPASSWORD=do-not-copy-this-literal\n', 'credential-like'),
            ('BOM_RELEASE=2026.10\n-----BEGIN ENCRYPTED PRIVATE KEY-----\nredacted\n', 'credential-like'),
            ('BOM_UNKNOWN=value\n', 'unknown, duplicate or malformed'),
            ('BOM_RELEASE=2026.10\nBOM_RELEASE=2026.11\n', 'unknown, duplicate or malformed'),
            ('BOM_RELEASE\n', 'unknown, duplicate or malformed'),
            ('BOM_JAVA_SHA256=not-a-checksum\n', 'checksum has an invalid format'),
        )
        for content, message in cases:
            with self.subTest(content=content):
                self.put(bom, content)
                with self.assertRaisesRegex(seed.SeedError, message):
                    self.collect()
                self.assertFalse(self.output.exists())

    def test_output_cannot_write_into_candidate_cache(self):
        self.output = self.cache / 'new-seed'
        with self.assertRaises(seed.SeedError):
            self.collect()
        self.assertFalse(self.output.exists())

    def test_build_work_cannot_write_into_source_or_cache(self):
        self.collect()
        for work in (self.project / 'new-work', self.cache / 'new-work'):
            with patch.object(seed, 'maven_identity', return_value=IDENTITY):
                with self.assertRaises(seed.SeedError):
                    seed.verify_build(self.output, 'mvn', work, seed.digest(self.output / 'seed.lock.json'))
            self.assertFalse(work.exists())

    def test_build_rechecks_original_lock_pin(self):
        self.collect()
        work = self.root / 'mutated-build'
        original_pin = seed.digest(self.output / 'seed.lock.json')
        def simulated_maven(command, **kwargs):
            project = Path(kwargs['cwd'])
            self.put(project / 'target/surefire-reports/TEST-example.xml', '<testsuite tests="1" failures="0" errors="0" skipped="0"/>')
            self.put(project / 'target/example.jar', 'fixture')
            lock = self.output / 'seed.lock.json'
            lock.write_text(lock.read_text() + ' ')
            return subprocess.CompletedProcess(command, 0)
        with patch.object(seed, 'maven_identity', return_value=IDENTITY), patch.object(seed.subprocess, 'run', side_effect=simulated_maven):
            with self.assertRaises(seed.SeedError):
                seed.verify_build(self.output, 'mvn', work, original_pin)
        self.assertFalse(json.loads((work / 'verification.json').read_text())['passed'])


if __name__ == '__main__':
    unittest.main()
