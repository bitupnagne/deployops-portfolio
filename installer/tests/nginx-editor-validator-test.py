"""Managed editor boundary tests; no live nginx, filesystem or network mutation."""
import argparse
import importlib.util
from pathlib import Path
import unittest

module_path = Path(__file__).resolve().parents[1] / "deploy-agent/web/nginx-config-validator.py"
spec = importlib.util.spec_from_file_location("nginx_editor_validator", module_path)
editor = importlib.util.module_from_spec(spec)
spec.loader.exec_module(editor)

BODY = '''# Deployment editor keeps comments and quoted strings.
upstream deploy_policy_editor {
    server 127.0.0.1:19001 max_fails=1 fail_timeout=10s;
    server 127.0.0.1:19002 max_fails=1 fail_timeout=10s;
}
server {
    listen 18091;
    server_name localhost;
    set $deploy_request_host $http_host;
    if ($deploy_request_host = "") { set $deploy_request_host $host; }
    add_header X-Editor "literal ; { } # still a value" always;
    location / {
        proxy_pass http://deploy_policy_editor;
        proxy_set_header Host $deploy_request_host;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header Forwarded "";
        proxy_set_header X-Forwarded-Port "";
        proxy_set_header X-Forwarded-Prefix "";
        proxy_set_header X-Forwarded-Ssl "";
    }
}
'''


class EditorBoundaryTest(unittest.TestCase):
    def options(self, **changes):
        values = dict(policy="editor", server_name="localhost", listen="18091", policy_type="REVERSE_PROXY", web_root="", tls="false", redirect_http="false", upstream=[("127.0.0.1", "19001"), ("127.0.0.1", "19002")])
        values.update(changes)
        return argparse.Namespace(**values)

    def test_quoted_comments_and_editable_directives(self):
        editor.validate(BODY.replace("location / {", "gzip on;\n    location / {"), self.options())
        editor.validate(BODY.replace('literal ; { } # still a value', ';'), self.options())

    def test_rejects_scope_and_identity_changes(self):
        mutations = [
            BODY + "include /etc/passwd;\n",
            BODY.replace("listen 18091;", "listen 18092;"),
            BODY.replace("server_name localhost;", "server_name other.local;"),
            BODY.replace("server_name localhost;", "server_name localhost;\n server_name other.local;"),
            BODY.replace("127.0.0.1:19002", "127.0.0.1:19003"),
            BODY.replace("proxy_pass http://deploy_policy_editor;", "proxy_pass http://169.254.169.254:80;"),
            BODY.replace("proxy_pass http://deploy_policy_editor;", "proxy_pass http://deploy_policy_other;"),
            BODY.replace("location / {", "location / {\n alias /etc/;"),
            BODY.replace("location / {", "location / {\n access_log /etc/cron.d/nginx;"),
            BODY.replace("location / {", "location / {\n include /etc/nginx/tls/editor/current/privkey.pem;"),
            BODY.replace("location / {", "location / {\n perl_set $x evil;"),
            BODY.replace("location / {", "location / {\n set $remote_addr 10.0.0.1;"),
            BODY.replace("$remote_addr;", "$proxy_add_x_forwarded_for;"),
            BODY.replace("$remote_addr;", '"\\$remote_addr";'),
            BODY.replace('proxy_set_header Forwarded "";', 'proxy_set_header Forwarded "for=10.0.0.1";'),
            BODY.replace('proxy_set_header Forwarded "";', ''),
            BODY + "# Generated by Deploy System. Request 1.\n",
            BODY + "\x00",
            BODY[:-3],
        ]
        for index, body in enumerate(mutations):
            with self.subTest(index=index):
                with self.assertRaises(ValueError):
                    editor.validate(body, self.options())

    def test_static_root_is_bound_to_deploy_root(self):
        body = "server { listen 18091; server_name localhost; location / { root /var/www/editor/current; try_files $uri $uri/ /index.html; } }\n"
        options = self.options(policy_type="STATIC_SPA", web_root="/var/www/editor", upstream=[])
        editor.validate(body, options)
        for replacement in ("/etc", "/var/www/other/current", "/var/www/editor/current/../../"):
            with self.subTest(root=replacement), self.assertRaises(ValueError):
                editor.validate(body.replace("/var/www/editor/current", replacement), options)
        for statement in ("try_files /../../../../etc/passwd =404;", "index ../../../../etc/passwd;", "try_files $arg_file =404;", "rewrite ^ /../../outside break;", "error_page 404 /../../outside;"):
            with self.subTest(statement=statement), self.assertRaises(ValueError):
                editor.validate(body.replace("try_files $uri $uri/ /index.html;", statement), options)
        with self.assertRaises(ValueError):
            editor.validate(body.replace("root /var/www/editor/current;", ""), options)
        for variant in ("server { listen 18091; server_name localhost; }", body.replace("location / {", "location /assets/ {")):
            with self.subTest(default_root=variant), self.assertRaises(ValueError):
                editor.validate(variant, options)
        with self.assertRaises(ValueError):
            editor.validate(BODY.replace("location / {", "location / { autoindex on; }\n location /api/ {"), self.options())

    def test_tls_paths_and_http_redirect_are_bound(self):
        body = BODY.replace("listen 18091;", "listen 18091 ssl http2;\n ssl_certificate /etc/nginx/tls/editor/current/fullchain.pem;\n ssl_certificate_key /etc/nginx/tls/editor/current/privkey.pem;")
        body = 'server { listen 80; server_name localhost; return 301 https://$host$request_uri; }\n' + body
        options = self.options(tls="true", redirect_http="true")
        editor.validate(body, options)
        for mutated in (body.replace("/editor/current/privkey.pem", "/other/current/privkey.pem"), body.replace("https://$host$request_uri", "https://external.local$request_uri")):
            with self.assertRaises(ValueError):
                editor.validate(mutated, options)
        with self.assertRaises(ValueError):
            editor.validate(body.replace("ssl_certificate ", "ssl_protocols TLSv1 TLSv1.1;\n ssl_certificate ", 1), options)


if __name__ == "__main__":
    unittest.main()
