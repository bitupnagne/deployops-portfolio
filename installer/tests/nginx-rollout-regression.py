"""Run under Linux root. All files and Nginx calls are isolated in a temporary fixture."""
import contextlib
import importlib.util
import io
import json
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

module_path = Path(__file__).resolve().parents[1] / "deploy-agent/web/nginx-rollout.py"
spec = importlib.util.spec_from_file_location("nginx_rollout", module_path)
rollout = importlib.util.module_from_spec(spec)
spec.loader.exec_module(rollout)

BODY = b'''# Generated by Deploy System. Request 71.
# server 198.18.5.1:8080; } upstream fake {
upstream app {
    server 198.18.5.1:8080 weight=2;
    server 198.18.5.2:8080 max_fails=2;
}
server {
    listen 80;
    add_header X-Literal "server 198.18.5.1:8080; { } # literal";
    location /api/ { proxy_pass http://app; }
    location /socket/ { proxy_pass http://app; proxy_set_header Upgrade $http_upgrade; }
}
'''


class LexerTests(unittest.TestCase):
    def test_single_upstream_requires_explicit_downtime_permission(self):
        body = b"upstream app { server 198.18.5.1:8080; }"
        with self.assertRaises(ValueError):
            rollout.drain_body(body, "198.18.5.1", 8080)
        self.assertEqual(rollout.drain_body(body, "198.18.5.1", 8080, True),
                         b"upstream app { server 198.18.5.1:8080 down; }")
        with self.assertRaises(ValueError):
            rollout.drain_body(body.replace(b";", b" down;"), "198.18.5.1", 8080, True)

    def test_preserves_comments_quoted_strings_locations_and_unselected_peer(self):
        changed = rollout.drain_body(BODY, "198.18.5.1", 8080)
        self.assertEqual(changed, BODY.replace(b"server 198.18.5.1:8080 weight=2;",
                                              b"server 198.18.5.1:8080 weight=2 down;"))

    def test_quotes_ipv6_and_other_upstream_are_supported(self):
        body = b'''upstream other { server 198.18.6.1:80; }
upstream app { server "[::1]:8080"; server [::2]:8080; }
server { location / { proxy_pass http://app; } }'''
        changed = rollout.drain_body(body, "::1", 8080)
        self.assertIn(b'server "[::1]:8080" down;', changed)
        self.assertIn(b'upstream other { server 198.18.6.1:80; }', changed)

    def test_ambiguous_missing_disabled_and_last_peer_refuse(self):
        cases = (
            BODY.replace(b"198.18.5.2", b"198.18.5.1"),
            BODY.replace(b"198.18.5.1", b"198.18.5.3"),
            BODY.replace(b"weight=2;", b"weight=2 down;"),
            BODY.replace(b"server 198.18.5.2:8080 max_fails=2;", b"server 198.18.5.2:8080 down;"),
        )
        for body in cases:
            with self.subTest(body=body), self.assertRaises(ValueError):
                rollout.drain_body(body, "198.18.5.1", 8080)


class TransitionTests(unittest.TestCase):
    def setUp(self):
        if os.geteuid() != 0:
            self.fail("Run this isolated filesystem test as Linux root; do not skip ownership checks.")
        self.temp = tempfile.TemporaryDirectory(prefix="nginx-rollout-fixture-")
        self.root = Path(self.temp.name)
        self.config_root = self.root / "conf"
        self.state_root = self.root / "state"
        self.config_root.mkdir(mode=0o755)
        self.config = self.config_root / "deploy-app.conf"
        self.config.write_bytes(BODY)
        self.config.chmod(0o640)
        self.state = self.state_root / "app.json"
        self.expected = rollout.digest(BODY)
        self.patches = [patch.object(rollout, "CONFIG_ROOT", self.config_root),
                        patch.object(rollout, "STATE_ROOT", self.state_root),
                        patch.object(rollout, "reload_nginx")]
        for item in self.patches:
            item.start()
        self.addCleanup(self.temp.cleanup)
        self.addCleanup(lambda: [item.stop() for item in reversed(self.patches)])

    def transition(self, action, generation="request-77", host="198.18.5.1"):
        with contextlib.redirect_stdout(io.StringIO()):
            rollout.transition(action, "app", generation, self.expected, host, 8080)

    def test_lost_responses_retry_without_extra_mutation_and_restore_exact_bytes(self):
        self.transition("drain")
        after = self.config.read_bytes()
        self.transition("drain")
        self.assertEqual(self.config.read_bytes(), after)
        self.assertEqual(self.config.stat().st_mode & 0o777, 0o640)
        self.transition("restore")
        self.assertEqual(self.config.read_bytes(), BODY)
        self.assertFalse(self.state.exists())
        self.transition("restore")
        self.assertEqual(self.config.read_bytes(), BODY)

    def test_explicit_single_upstream_downtime_restores_without_weakening_default(self):
        original = BODY.replace(b"    server 198.18.5.2:8080 max_fails=2;\n", b"")
        self.config.write_bytes(original)
        self.expected = rollout.digest(original)
        with self.assertRaises(ValueError):
            self.transition("drain")
        self.assertEqual(self.config.read_bytes(), original)
        self.assertFalse(self.state.exists())
        with contextlib.redirect_stdout(io.StringIO()):
            rollout.transition("drain", "app", "request-77", self.expected, "198.18.5.1", 8080, True)
        self.assertTrue(json.loads(self.state.read_text())["allowZeroUpstreams"])
        with self.assertRaises(ValueError):
            self.transition("drain")  # Retry cannot silently drop the approved exception.
        with contextlib.redirect_stdout(io.StringIO()):
            rollout.transition("drain", "app", "request-77", self.expected, "198.18.5.1", 8080, True)
        self.transition("restore")
        self.assertEqual(self.config.read_bytes(), original)
        self.assertFalse(self.state.exists())

    def test_other_generation_or_peer_never_takes_over_pending_state(self):
        self.transition("drain")
        after = self.config.read_bytes()
        for action, generation, host in (("drain", "other", "198.18.5.1"),
                                         ("restore", "other", "198.18.5.1"),
                                         ("drain", "request-77", "198.18.5.2")):
            with self.subTest(action=action, generation=generation, host=host), self.assertRaises(ValueError):
                self.transition(action, generation, host)
            self.assertEqual(self.config.read_bytes(), after)

    def test_drain_reload_failure_compensates_and_failed_compensation_retains_state(self):
        rollout.reload_nginx.side_effect = [ValueError("reload"), None]
        with self.assertRaises(ValueError):
            self.transition("drain")
        self.assertEqual(self.config.read_bytes(), BODY)
        self.assertFalse(self.state.exists())
        rollout.reload_nginx.side_effect = [ValueError("reload"), ValueError("restore reload")]
        with self.assertRaises(ValueError):
            self.transition("drain")
        self.assertTrue(self.state.exists())
        self.assertEqual(self.config.read_bytes(), BODY)
        rollout.reload_nginx.side_effect = None
        self.transition("restore")
        self.assertFalse(self.state.exists())

    def test_restore_reload_failure_is_retryable_with_original_config_already_written(self):
        self.transition("drain")
        rollout.reload_nginx.side_effect = ValueError("reload failed")
        with self.assertRaises(ValueError):
            self.transition("restore")
        self.assertEqual(self.config.read_bytes(), BODY)
        self.assertTrue(self.state.exists())
        rollout.reload_nginx.side_effect = None
        self.transition("restore")
        self.assertFalse(self.state.exists())

    def test_external_edit_is_preserved_and_missing_state_cannot_guess_a_restore(self):
        self.transition("drain")
        external = self.config.read_bytes() + b"# external change\n"
        self.config.write_bytes(external)
        with self.assertRaises(ValueError):
            self.transition("restore")
        self.assertEqual(self.config.read_bytes(), external)
        self.state.unlink()
        with self.assertRaises(ValueError):
            self.transition("restore")
        self.assertEqual(self.config.read_bytes(), external)

    def test_malformed_state_and_mismatched_hash_cannot_write_config(self):
        self.transition("drain")
        before = self.config.read_bytes()
        valid = json.loads(self.state.read_text())
        malformed = [None, [], {"generation": "request-77"},
                     dict(valid, before=17), dict(valid, port=True),
                     dict(valid, afterSha="a" * 64), dict(valid, policy="other"),
                     dict(valid, mode=0o777), dict(valid, host=[])]
        for document in malformed:
            self.state.write_text(json.dumps(document))
            with self.subTest(document=document), self.assertRaises(ValueError):
                self.transition("restore")
            self.assertEqual(self.config.read_bytes(), before)

    def test_symlinks_writable_files_and_unmanaged_configs_fail_before_reload(self):
        original = self.root / "original"
        original.write_bytes(BODY)
        self.config.unlink()
        self.config.symlink_to(original)
        with self.assertRaises((ValueError, OSError)):
            self.transition("drain")
        self.config.unlink()
        self.config.write_bytes(BODY)
        self.config.chmod(0o666)
        with self.assertRaises(ValueError):
            self.transition("drain")
        self.config.chmod(0o644)
        self.config.write_bytes(BODY.replace(b"# Generated", b"# Unmanaged"))
        with self.assertRaises(ValueError):
            self.transition("drain")
        rollout.reload_nginx.assert_not_called()


if __name__ == "__main__":
    unittest.main()
