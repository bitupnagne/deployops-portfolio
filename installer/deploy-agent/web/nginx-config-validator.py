"""Validate an editable managed-site body without evaluating nginx directives.

The OS service and other virtual hosts remain outside this editor's scope. nginx -t
is still required: this parser checks ownership boundaries, not nginx semantics.
"""
import argparse
import hashlib
import ipaddress
import os
from pathlib import Path
import re
import sys


def reject(message):
    raise ValueError(message)


class Delimiter(str):
    pass


def tokens(text):
    result, word = [], []
    quote, escaped, started = None, False, False
    index = 0
    while index < len(text):
        char = text[index]
        if escaped:
            # Match nginx's value decoding. Unknown escapes retain the slash;
            # in particular \$remote_addr is not the trusted $remote_addr value.
            word.append({"t": "\t", "r": "\r", "n": "\n", "\\": "\\", "'": "'", '"': '"'}.get(char, "\\" + char))
            escaped = False
        elif char == "\\":
            escaped, started = True, True
        elif quote:
            if char == quote:
                quote = None
            else:
                word.append(char)
        elif char in "\"'":
            quote, started = char, True
        elif char == "#":
            if started:
                result.append("".join(word)); word, started = [], False
            end = text.find("\n", index)
            index = len(text) if end < 0 else end
            continue
        elif char.isspace() or char in ";{}":
            if started:
                result.append("".join(word)); word, started = [], False
            if char in ";{}":
                result.append(Delimiter(char))
        else:
            word.append(char); started = True
        index += 1
    if quote or escaped:
        reject("닫히지 않은 따옴표 또는 escape가 있습니다.")
    if started:
        result.append("".join(word))
    return result


def parse(text):
    stream, index = tokens(text), 0

    def block(nested=False):
        nonlocal index
        nodes = []
        while index < len(stream):
            args = []
            while index < len(stream) and not isinstance(stream[index], Delimiter):
                args.append(stream[index]); index += 1
            if index == len(stream):
                reject("지시문 끝에 세미콜론이 필요합니다.")
            separator = stream[index]; index += 1
            if separator == "}":
                if args or not nested:
                    reject("블록 경계가 올바르지 않습니다.")
                return nodes
            if not args:
                reject("빈 지시문은 사용할 수 없습니다.")
            nodes.append((args[0], args[1:], block(True) if separator == "{" else None))
        if nested:
            reject("닫히지 않은 블록이 있습니다.")
        return nodes
    return block()


COMMON = set("client_max_body_size client_body_timeout client_header_timeout keepalive_timeout keepalive_requests send_timeout sendfile tcp_nopush tcp_nodelay types_hash_max_size server_tokens gzip gzip_vary gzip_proxied gzip_comp_level gzip_buffers gzip_http_version gzip_min_length gzip_types etag expires add_header allow deny limit_except satisfy autoindex index try_files return rewrite error_page proxy_pass proxy_http_version proxy_set_header proxy_hide_header proxy_pass_header proxy_connect_timeout proxy_read_timeout proxy_send_timeout proxy_buffering proxy_request_buffering proxy_buffer_size proxy_buffers proxy_busy_buffers_size proxy_max_temp_file_size proxy_next_upstream proxy_next_upstream_tries proxy_next_upstream_timeout proxy_redirect proxy_cookie_path proxy_cookie_domain proxy_ssl_server_name proxy_ssl_name proxy_ssl_verify proxy_ssl_protocols proxy_socket_keepalive ssl_protocols ssl_ciphers ssl_prefer_server_ciphers ssl_session_timeout ssl_session_cache ssl_session_tickets ssl_buffer_size ssl_stapling ssl_stapling_verify http2 absolute_redirect port_in_redirect server_name_in_redirect charset default_type merge_slashes reset_timedout_connection lingering_close lingering_time lingering_timeout keepalive_disable chunked_transfer_encoding add_trailer".split())
PROTECTED_HEADERS = {"x-forwarded-for": "$remote_addr", "forwarded": "", "x-forwarded-port": "", "x-forwarded-prefix": "", "x-forwarded-ssl": ""}


def endpoint(host, port):
    try:
        host = str(ipaddress.ip_address(host))
    except ValueError:
        host = host.lower()
    return host, int(port)


def target(value):
    match = re.fullmatch(r"(?:\[([^]]+)\]|([^:/]+)):(\d{1,5})", value)
    if not match or not 1 <= int(match[3]) <= 65535:
        reject("upstream 주소와 포트를 확인해 주세요.")
    return endpoint(match[1] or match[2], match[3])


def validate(text, options):
    encoded = text.encode("utf-8")
    if not encoded or len(encoded) > 61440 or any(ord(c) < 32 and c not in "\n\t" for c in text):
        reject("설정은 LF 형식의 UTF-8 텍스트이며 최대 60KiB여야 합니다.")
    if "${" in text or re.search(r"(?im)^\s*#\s*Generated by Deploy System", text):
        reject("관리용 헤더 또는 중괄호 변수 표기는 사용할 수 없습니다.")
    nodes = parse(text)
    expected = [endpoint(host, port) for host, port in options.upstream]
    upstream_name = "deploy_policy_" + re.sub("[^A-Za-z0-9]", "_", options.policy)
    upstreams = {}
    servers = []
    for name, args, children in nodes:
        if name == "upstream" and children is not None and len(args) == 1:
            if args[0] in upstreams or not re.fullmatch(re.escape(upstream_name) + r"(?:_\d+)?", args[0]):
                reject("upstream 이름은 이 정책의 관리 이름을 사용해야 합니다.")
            actual = []
            for directive, values, nested in children:
                if nested is not None:
                    reject("upstream에 중첩 블록을 사용할 수 없습니다.")
                if directive == "server" and values:
                    actual.append(target(values[0]))
                    if any(not re.fullmatch(r"(?:max_fails=\d{1,2}|fail_timeout=\d{1,3}s|weight=\d{1,3}|backup|down)", v) for v in values[1:]):
                        reject("upstream server 옵션을 확인해 주세요.")
                elif directive not in ("keepalive", "keepalive_requests", "keepalive_timeout", "least_conn", "ip_hash", "zone"):
                    reject("허용되지 않은 upstream 지시문입니다: " + directive)
            if actual != expected:
                reject("설정문의 WAS 주소·순서는 선택한 WAS 목록과 같아야 합니다.")
            upstreams[args[0]] = actual
        elif name == "server" and not args and children is not None:
            servers.append(children)
        else:
            reject("최상위에는 이 정책의 upstream과 server 블록만 사용할 수 있습니다.")
    if not servers or len(servers) > 2 or len(upstreams) > 1:
        reject("정책에는 서비스 server와 선택적인 HTTP 전환 server만 사용할 수 있습니다.")
    primary_count, redirect_count, proxy_count = 0, 0, 0

    def safe_uri(value):
        return bool(re.fullmatch(r"(?:/[A-Za-z0-9._/-]*|@[A-Za-z0-9_-]+)", value)) and ".." not in value.split("/")

    def walk(children, context, inherited_root=False):
        nonlocal proxy_count
        proxy_headers, has_proxy = {}, False
        managed_root = inherited_root or any(name == "root" for name, _, _ in children)
        direct_return = any(name == "return" for name, _, _ in children)
        if context == "location" and not managed_root and not direct_return and not any(name == "proxy_pass" for name, _, _ in children):
            reject("정적 파일 location에는 관리 root 또는 관리 root 상속이 필요합니다.")
        for name, args, nested in children:
            if nested is not None:
                if name == "location" and context == "server" and args:
                    walk(nested, "location", managed_root)
                elif name == "if" and context in ("server", "location") and " ".join(args) == '($deploy_request_host = )':
                    if nested != [("set", ["$deploy_request_host", "$host"], None)]:
                        reject("Host 보정 if 블록은 관리 템플릿 형식을 사용해야 합니다.")
                else:
                    reject("허용되지 않은 설정 블록입니다: " + name)
                continue
            if name in ("listen", "server_name") and context == "server":
                continue  # Checked against the typed identity below.
            if name == "root":
                if options.policy_type == "REVERSE_PROXY" or args != [options.web_root + "/current"]:
                    reject("root는 선택한 정적 서비스의 배포 경로/current와 같아야 합니다.")
            elif name == "try_files":
                if not managed_root or len(args) < 2 or any(value not in ("$uri", "$uri/") and not safe_uri(value) for value in args[:-1]) or not (re.fullmatch(r"=[245]\d\d", args[-1]) or safe_uri(args[-1])):
                    reject("try_files는 관리 root에서 $uri, $uri/ 및 안전한 내부 경로만 사용할 수 있습니다.")
            elif name == "index":
                if not managed_root or not args or any(not re.fullmatch(r"[A-Za-z0-9_-][A-Za-z0-9._-]*", value) or ".." in value for value in args):
                    reject("index에는 관리 root 안의 파일 이름만 지정할 수 있습니다.")
            elif name == "rewrite":
                if len(args) not in (2, 3) or not safe_uri(args[1]) or (len(args) == 3 and args[2] not in ("last", "break", "redirect", "permanent")):
                    reject("rewrite 대상은 변수나 상위 경로가 없는 내부 URI여야 합니다.")
            elif name == "error_page":
                if len(args) < 2 or not safe_uri(args[-1]) or any(not re.fullmatch(r"=?[245]\d\d|=", value) for value in args[:-1]):
                    reject("error_page 대상은 안전한 내부 URI여야 합니다.")
            elif name == "ssl_protocols":
                if not args or len(set(args)) != len(args) or any(value not in ("TLSv1.2", "TLSv1.3") for value in args):
                    reject("TLS 프로토콜은 TLSv1.2 또는 TLSv1.3만 사용할 수 있습니다.")
            elif name in ("ssl_certificate", "ssl_certificate_key"):
                leaf = "fullchain.pem" if name == "ssl_certificate" else "privkey.pem"
                if options.tls != "true" or args != ["/etc/nginx/tls/" + options.policy + "/current/" + leaf]:
                    reject("인증서는 이 정책의 관리 TLS 경로를 사용해야 합니다.")
            elif name == "set":
                if args != ["$deploy_request_host", "$http_host"]:
                    reject("사용자 정의 set은 지원하지 않습니다. Host 보정 템플릿을 사용해 주세요.")
            elif name == "access_log":
                if args != ["off"]:
                    reject("편집기에서 로그 파일 경로를 지정할 수 없습니다.")
            elif name == "proxy_pass":
                if len(args) != 1 or not expected:
                    reject("proxy_pass는 선택한 WAS 목록을 사용해야 합니다.")
                match = re.fullmatch(r"http://([^/]+)(/[^\s]*)?", args[0])
                if not match or (match[1] not in upstreams and (len(expected) != 1 or target(match[1]) != expected[0])):
                    reject("proxy_pass 주소는 선택한 WAS 또는 이 정책의 upstream을 사용해야 합니다.")
                has_proxy = True; proxy_count += 1
            elif name == "proxy_set_header":
                if len(args) != 2:
                    reject("proxy_set_header는 헤더 이름과 값을 지정해야 합니다.")
                key = args[0].lower()
                if key in PROTECTED_HEADERS:
                    if key in proxy_headers or args[1] != PROTECTED_HEADERS[key]:
                        reject("접속망 판정용 전달 헤더는 관리 템플릿 값을 유지해야 합니다.")
                    proxy_headers[key] = args[1]
            elif name not in COMMON:
                reject("지원하지 않는 지시문입니다: " + name)
            # All file-reading/writing directives are excluded except managed root/TLS.
        if has_proxy and proxy_headers != PROTECTED_HEADERS:
            reject("프록시 블록에 접속망 판정용 전달 헤더 템플릿이 필요합니다.")

    for children in servers:
        names = [args for name, args, nested in children if name == "server_name" and nested is None]
        listens = [args for name, args, nested in children if name == "listen" and nested is None]
        if names != [[options.server_name]] or len(listens) != 1:
            reject("server_name과 listen은 선택한 정책의 도메인·포트와 일치해야 합니다.")
        listen = listens[0]
        if not listen or listen[0] not in (options.listen, "80") or any(v not in ("ssl", "http2") for v in listen[1:]):
            reject("listen 포트 또는 옵션이 정책과 다릅니다.")
        if listen[0] == options.listen:
            primary_count += 1
            if not any(name in ("root", "return") for name, _, _ in children) and not any(name == "location" and args == ["/"] for name, args, _ in children):
                reject("기본 URI는 관리 root, return 또는 location /에서 명시적으로 처리해야 합니다.")
            if ("ssl" in listen) != (options.tls == "true"):
                reject("listen의 TLS 사용 여부가 정책과 다릅니다.")
            for directive in ("ssl_certificate", "ssl_certificate_key"):
                if options.tls == "true" and sum(name == directive for name, _, _ in children) != 1:
                    reject("TLS 서비스에는 관리 인증서와 개인키 지시문이 필요합니다.")
        else:
            redirect_count += 1
            if options.tls != "true" or options.redirect_http != "true" or listen != ["80"] or children != [("listen", ["80"], None), ("server_name", [options.server_name], None), ("return", ["301", "https://$host$request_uri"], None)]:
                reject("보조 server는 HTTP→HTTPS 전환 템플릿만 사용할 수 있습니다.")
        walk(children, "server")
    if primary_count != 1 or redirect_count > 1 or (expected and not proxy_count):
        reject("서비스 server 또는 WAS 프록시 구성이 정책과 다릅니다.")


def main():
    if len(sys.argv) == 5 and sys.argv[1] == "freeze":
        # Open every staging directory without following symlinks. Hold descriptors
        # while reading so a deploy-account rename cannot redirect this root read.
        source, destination, digest = sys.argv[2:]
        directory = os.open("/", os.O_RDONLY | os.O_DIRECTORY)
        try:
            parts = Path(source).parts[1:]
            for part in parts[:-1]:
                child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=directory)
                os.close(directory); directory = child
            source_fd = os.open(parts[-1], os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=directory)
            with os.fdopen(source_fd, "rb") as stream:
                import stat
                if not stat.S_ISREG(os.fstat(stream.fileno()).st_mode):
                    reject("설정 staging 파일은 일반 파일이어야 합니다.")
                body = stream.read(61441)
            if not body or len(body) > 61440 or hashlib.sha256(body).hexdigest() != digest:
                reject("승인된 설정문의 해시 또는 크기가 다릅니다.")
            destination_fd = os.open(destination, os.O_WRONLY | os.O_TRUNC | os.O_NOFOLLOW)
            with os.fdopen(destination_fd, "wb") as stream:
                stream.write(body)
        except (ValueError, OSError) as ex:
            print("설정문 복사 실패: " + str(ex), file=sys.stderr)
            return 1
        finally:
            os.close(directory)
        return 0
    parser = argparse.ArgumentParser()
    parser.add_argument("file")
    for key in ("policy", "server-name", "listen", "policy-type", "web-root", "tls", "redirect-http"):
        parser.add_argument("--" + key, required=True)
    parser.add_argument("--upstream", nargs=2, action="append", default=[])
    options = parser.parse_args()
    try:
        validate(Path(options.file).read_bytes().decode("utf-8", errors="strict"), options)
    except (ValueError, OSError) as ex:
        print("설정문 검증 실패: " + str(ex), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
