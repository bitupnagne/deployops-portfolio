#!/bin/bash
# deploy-web-proxy.sh — PROXY_RELOAD 배포 에이전트 (SSR: WAS가 화면까지, WEB은 리버스 프록시만).
#   배포할 산출물이 없으므로 nginx 리버스프록시 설정을 (선택적으로) 갱신하고 검증 후 리로드한다.
#   render 모드는 upstream 으로 server 블록을 다시 쓰고, reload 모드는 설정 변경 없이 검증+리로드만 한다.
#   실패(nginx -t / reload) 시 직전 설정으로 즉시 되돌린다. 컨테이너를 쓰지 않는다.
set -euo pipefail

ACTION=""
UPSTREAM=""
SERVER_NAME="_"
LISTEN_PORT="80"
NGINX_CONF_PATH=""
CONF_NAME="proxy"
BACKUP_ROOT="/var/backups/deploy-system/nginx-proxy"
KEEP_BACKUPS=10
LOCK_FILE="/var/lock/deploy-ops-web-proxy.lock"
HEALTH_PORT=""
HEALTH_PATH="/"
HEALTH_HOST=""
# 현재 기본 upstream failover 예산(연결 3초 × 2) 이후 응답을 받을 여유를 둔다.
HEALTH_MAX_TIME=10
# 10회 × 10초 + 대기 9회 × 3초 = 최대 127초. SSH 기본 240초보다 짧게 유지한다.
HEALTH_ATTEMPTS=10

usage(){
  cat <<'EOF'
Usage:
  deploy-web-proxy.sh deploy --upstream HOST:PORT [--server-name NAME] [--listen PORT] [--conf-name NAME] [--nginx-conf PATH]
  deploy-web-proxy.sh reload [--health-port PORT] [--health-path PATH] [--health-host HOST]
  deploy-web-proxy.sh status [--health-port PORT] [--health-path PATH] [--health-host HOST]
  Deploy/reload require successful HTTP health. Status only reads nginx and HTTP health.
EOF
}

safe_path(){ [[ "$1" =~ ^/[A-Za-z0-9._/+:-]+$ ]]; }
# ★ 설정 파일은 conf.d 안으로 못박는다. sudoers 는 <스크립트>만 제한할 뿐 인자는 막지 못하므로,
#   임의 절대경로를 받으면 deploy 계정이 root 로 아무 파일이나 덮어쓸 수 있다
#   (예: --nginx-conf /etc/nginx/nginx.conf 로 주 설정 파괴).
#   deploy-nginx-policy.sh 는 처음부터 경로를 고정하고 있었다 — 같은 기준으로 맞춘다.
safe_conf_path(){ [[ "$1" =~ ^/etc/nginx/conf\.d/[A-Za-z0-9][A-Za-z0-9._-]*\.conf$ ]]; }
safe_name(){ [[ "$1" =~ ^[A-Za-z0-9._-]+$ ]]; }
safe_server_name(){ [[ "$1" =~ ^[A-Za-z0-9._*-]+$ ]]; }
safe_upstream(){ [[ "$1" =~ ^[A-Za-z0-9._-]+:[0-9]{1,5}$ ]]; }
require_root(){ [[ "${EUID}" -eq 0 ]] || { echo "Run as root."; exit 1; }; }

parse_args(){
  [[ "$#" -gt 0 ]] || { usage; exit 1; }
  ACTION="$1"; shift
  while [[ "$#" -gt 0 ]]; do
    case "$1" in
      --upstream|--server-name|--listen|--conf-name|--nginx-conf|--health-port|--health-path|--health-host)
        [[ "$#" -ge 2 && -n "$2" ]] || { echo "Missing value for $1"; exit 1; } ;;
    esac
    case "$1" in
      --upstream) UPSTREAM="$2"; shift 2 ;;
      --server-name) SERVER_NAME="$2"; shift 2 ;;
      --listen) LISTEN_PORT="$2"; shift 2 ;;
      --conf-name) CONF_NAME="$2"; shift 2 ;;
      --nginx-conf) NGINX_CONF_PATH="$2"; shift 2 ;;
      --health-port) HEALTH_PORT="$2"; shift 2 ;;
      --health-path) HEALTH_PATH="$2"; shift 2 ;;
      --health-host) HEALTH_HOST="$2"; shift 2 ;;
      -h|--help) usage; exit 0 ;;
      *) echo "Unknown argument: $1"; usage; exit 1 ;;
    esac
  done
}

validate_health(){
  if [[ -z "$HEALTH_PORT" ]]; then
    if [[ "$ACTION" == "deploy" ]]; then HEALTH_PORT="$LISTEN_PORT"; else HEALTH_PORT="80"; fi
  fi
  [[ "$HEALTH_PORT" =~ ^[0-9]{1,5}$ ]] && (( 10#$HEALTH_PORT >= 1 && 10#$HEALTH_PORT <= 65535 )) \
    || { echo "Invalid health port: $HEALTH_PORT"; exit 1; }
  [[ "$HEALTH_PATH" == /* && "$HEALTH_PATH" != //* && ${#HEALTH_PATH} -le 2048 \
    && ! "$HEALTH_PATH" =~ [[:space:][:cntrl:]#] ]] \
    || { echo "Invalid health path."; exit 1; }
  command -v curl >/dev/null 2>&1 || { echo "curl is required for proxy health checks."; exit 1; }
  if [[ -n "$HEALTH_HOST" ]]; then
    [[ ${#HEALTH_HOST} -le 253 && "$HEALTH_HOST" =~ ^[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$ ]] \
      || { echo "Invalid proxy HTTP Host."; exit 1; }
  fi
}

check_proxy_health(){
  local attempt
  local -a host_args=()
  if [[ -n "$HEALTH_HOST" ]]; then host_args=(-H "Host: ${HEALTH_HOST}"); fi
  # Fixed loopback target and bounded retries: no remote URL or privileged command input.
  for ((attempt=1; attempt<=HEALTH_ATTEMPTS; attempt++)); do
    if curl -q --globoff --noproxy '*' -fsS --connect-timeout 3 --max-time "$HEALTH_MAX_TIME" \
        "${host_args[@]}" "http://127.0.0.1:${HEALTH_PORT}${HEALTH_PATH}" >/dev/null; then
      echo "Proxy HTTP health check passed (port=${HEALTH_PORT}, path=${HEALTH_PATH})."
      return 0
    fi
    if (( attempt < HEALTH_ATTEMPTS )); then sleep 3; fi
  done
  echo "Proxy HTTP health check failed after ${HEALTH_ATTEMPTS} attempts (port=${HEALTH_PORT}, path=${HEALTH_PATH})." >&2
  return 1
}

nginx_ready(){
  command -v nginx >/dev/null 2>&1 || { echo "nginx is required."; exit 1; }
}

CONF_MARKER="# Generated by Deploy System deploy-web-proxy.sh"

# ★ conf.d 에 설정을 쓰는 주체가 넷이다(설치기 officesystem.conf · 승인형 정책 ·
#   이 스크립트 · deploy-web-app.sh). 파일명 규칙이 겹쳐서 서로를 덮어쓸 수 있는데,
#   특히 <승인 없이 도는 이 스크립트가 승인받은 정책 파일을 덮는> 것이 위험하다.
#   첫 줄 표식이 내 것이 아니면 손대지 않는다.
assert_owns_config(){
  local target="$1"
  [[ -f "$target" ]] || return 0
  if head -n 1 "$target" | grep -qxF "$CONF_MARKER"; then
    return 0
  fi
  echo "다른 생성기가 만든 설정이라 덮어쓰지 않습니다: $target" >&2
  echo "  첫 줄: $(head -n 1 "$target")" >&2
  echo "  이름을 바꾸거나(--conf-name) 해당 설정을 만든 경로에서 변경하세요." >&2
  exit 1
}

# ★ 같은 (listen 포트, server_name) 을 잡은 server 블록이 이미 있으면 nginx 는 나중에
#   로드되는 쪽을 "conflicting server name" 경고와 함께 무시한다. nginx -t 는 통과하므로
#   배포는 성공으로 보이고 서비스만 되지 않는다 — 운영에서 가장 찾기 어려운 부류다.
assert_no_conflicting_server(){
  local target="$1" port="$2" name="$3" other escaped
  escaped="${name//./\\.}"
  for other in /etc/nginx/conf.d/*.conf; do
    [[ -f "$other" && "$other" != "$target" ]] || continue
    grep -qE "^[[:space:]]*listen[[:space:]]+(\[::\]:)?${port}([^0-9]|$)" "$other" || continue
    grep -qE "^[[:space:]]*server_name[[:space:]]+${escaped}[[:space:]]*;" "$other" || continue
    echo "이미 같은 포트($port)와 server_name($name) 을 잡은 설정이 있습니다: $other" >&2
    echo "  nginx 는 나중에 로드되는 쪽을 무시한다 — 배포는 성공하는데 서비스되지 않는다." >&2
    exit 1
  done
}

resolve_conf_path(){
  if [[ -n "$NGINX_CONF_PATH" ]]; then
    safe_conf_path "$NGINX_CONF_PATH" \
      || { echo "nginx config path must be /etc/nginx/conf.d/<name>.conf: $NGINX_CONF_PATH"; exit 1; }
    echo "$NGINX_CONF_PATH"; return 0
  fi
  safe_name "$CONF_NAME" || { echo "Invalid conf name: $CONF_NAME"; exit 1; }
  echo "/etc/nginx/conf.d/deploy-${CONF_NAME}.conf"
}

validate_inputs(){
  safe_server_name "$SERVER_NAME" || { echo "Invalid server name: $SERVER_NAME"; exit 1; }
  safe_upstream "$UPSTREAM" || { echo "Invalid upstream (HOST:PORT): $UPSTREAM"; exit 1; }
  [[ "$LISTEN_PORT" =~ ^[0-9]{1,5}$ ]] && (( 10#$LISTEN_PORT >= 1 && 10#$LISTEN_PORT <= 65535 )) \
    || { echo "Invalid listen port: $LISTEN_PORT"; exit 1; }
}

render_config(){
  local target="$1"
  validate_inputs
  install -d -m 755 "$(dirname "$target")"
  cat > "$target" <<EOF
${CONF_MARKER}
server {
    listen ${LISTEN_PORT};
    server_name ${SERVER_NAME};

    location / {
        proxy_pass http://${UPSTREAM};
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        # ★★ 덮어쓰기. append 하면 클라이언트가 XFF 최좌측을 정할 수 있고,
        #    오피스 AccessZone 이 그것으로 내부/외부망을 판정해 OTP 강제가 우회된다.
        proxy_set_header X-Forwarded-For \$remote_addr;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF
}

restore_config(){
  local target="$1" backup="$2"
  if [[ -f "$backup" ]]; then
    cp -f "$backup" "$target"
  else
    rm -f "$target"
  fi
}

test_and_reload(){
  local target="$1" backup="$2"
  if ! nginx -t; then
    echo "nginx -t failed. Restoring previous nginx config."
    restore_config "$target" "$backup"
    nginx -t || true
    exit 1
  fi
  if ! systemctl reload nginx; then
    echo "nginx reload failed. Restoring previous nginx config."
    restore_config "$target" "$backup"
    nginx -t || true
    systemctl reload nginx || true
    exit 1
  fi
  echo "nginx reloaded (proxy)."
}

run_deploy(){
  [[ -n "$UPSTREAM" ]] || { echo "--upstream is required for deploy."; exit 1; }
  nginx_ready
  validate_inputs
  local target backup
  target="$(resolve_conf_path)"
  assert_owns_config "$target"
  assert_no_conflicting_server "$target" "$LISTEN_PORT" "$SERVER_NAME"
  # 백업을 conf.d 안에 두면 무한히 쌓인다(.conf 로 끝나지 않아 로드되지는 않지만
  # 아무도 지우지 않는다). 다른 에이전트와 같이 /var/backups 로 빼고 보관 개수를 제한한다.
  install -d -m 700 "$BACKUP_ROOT"
  backup="${BACKUP_ROOT}/$(basename "$target").bak-$(date +%Y%m%d%H%M%S)"
  if [[ -f "$target" ]]; then cp -f "$target" "$backup"; fi
  render_config "$target"
  test_and_reload "$target" "$backup"
  if ! check_proxy_health; then
    echo "Restoring previous proxy config after failed HTTP health check."
    restore_config "$target" "$backup"
    nginx -t && systemctl reload nginx || true
    exit 1
  fi
  prune_backups
}

prune_backups(){
  ls -1dt "$BACKUP_ROOT"/*.bak-* 2>/dev/null | tail -n "+$((KEEP_BACKUPS + 1))" | while read -r old; do
    rm -f "$old"
  done
}

run_reload(){
  nginx_ready
  if ! nginx -t; then
    echo "nginx -t failed."
    exit 1
  fi
  systemctl reload nginx || { echo "nginx reload failed."; exit 1; }
  echo "nginx reloaded (proxy reload-only)."
  check_proxy_health || exit 1
}

run_status(){
  nginx_ready
  local nginx_active=false http_healthy=false
  local -a host_args=()
  if [[ -n "$HEALTH_HOST" ]]; then host_args=(-H "Host: ${HEALTH_HOST}"); fi
  if systemctl is-active --quiet nginx; then nginx_active=true; fi
  if curl -q --globoff --noproxy '*' -fsS --connect-timeout 3 --max-time "$HEALTH_MAX_TIME" \
      "${host_args[@]}" "http://127.0.0.1:${HEALTH_PORT}${HEALTH_PATH}" >/dev/null 2>&1; then http_healthy=true; fi
  printf 'ARTIFACT_TYPE=PROXY_RELOAD\nNGINX_ACTIVE=%s\nHTTP_HEALTHY=%s\n' "$nginx_active" "$http_healthy"
}

main(){
  require_root
  parse_args "$@"
  validate_health
  # 상태 조회는 잠금 파일·설정 변경·리로드 없이 한 번만 HTTP를 확인한다.
  if [[ "$ACTION" == "status" ]]; then run_status; return; fi
  # static · nginx-policy 와 같은 이유로 직렬화한다. 셋이 같은 nginx 를 건드리므로
  # 겹치면 서로의 중간 상태에서 nginx -t / reload 를 하게 된다.
  command -v flock >/dev/null 2>&1 || { echo "flock is required."; exit 1; }
  exec 8>/var/lock/deploy-ops-nginx.lock
  flock -n 8 || { echo "Another WEB nginx operation is in progress."; exit 1; }
  exec 9>"$LOCK_FILE"
  flock -n 9 || { echo "Another WEB proxy operation is in progress."; exit 1; }
  case "$ACTION" in
    deploy) run_deploy ;;
    reload) run_reload ;;
    *) echo "Unsupported action: $ACTION"; usage; exit 1 ;;
  esac
}

main "$@"
