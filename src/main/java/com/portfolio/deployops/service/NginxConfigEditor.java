/** 편집 원문과 검토용 템플릿을 다룬다. 최종 대상 환경의 nginx -t는 WEB 에이전트가 수행한다. */
final class NginxConfigEditor {
    static final int MAX_BYTES = 61440;
    private static final Set<String> DIRECTIVES = Set.of(
        "absolute_redirect", "access_log", "add_header", "add_trailer", "allow", "autoindex",
        "charset", "chunked_transfer_encoding", "client_body_timeout", "client_header_timeout", "client_max_body_size", "default_type",
        "deny", "error_page", "etag", "expires", "gzip", "gzip_buffers",
        "gzip_comp_level", "gzip_http_version", "gzip_min_length", "gzip_proxied", "gzip_types", "gzip_vary",
        "http2", "if", "index", "ip_hash", "keepalive", "keepalive_disable",
        "keepalive_requests", "keepalive_timeout", "least_conn", "limit_except", "lingering_close", "lingering_time",
        "lingering_timeout", "listen", "location", "merge_slashes", "port_in_redirect", "proxy_buffer_size",
        "proxy_buffering", "proxy_buffers", "proxy_busy_buffers_size", "proxy_connect_timeout", "proxy_cookie_domain", "proxy_cookie_path",
        "proxy_hide_header", "proxy_http_version", "proxy_max_temp_file_size", "proxy_next_upstream", "proxy_next_upstream_timeout", "proxy_next_upstream_tries",
        "proxy_pass", "proxy_pass_header", "proxy_read_timeout", "proxy_redirect", "proxy_request_buffering", "proxy_send_timeout",
        "proxy_set_header", "proxy_socket_keepalive", "proxy_ssl_name", "proxy_ssl_protocols", "proxy_ssl_server_name", "proxy_ssl_verify",
        "reset_timedout_connection", "return", "rewrite", "root", "satisfy", "send_timeout",
        "sendfile", "server", "server_name", "server_name_in_redirect", "server_tokens", "set",
        "ssl_buffer_size", "ssl_certificate", "ssl_certificate_key", "ssl_ciphers", "ssl_prefer_server_ciphers", "ssl_protocols",
        "ssl_session_cache", "ssl_session_tickets", "ssl_session_timeout", "ssl_stapling", "ssl_stapling_verify", "tcp_nodelay",
        "tcp_nopush", "try_files", "types_hash_max_size", "upstream", "zone"
    );

    private NginxConfigEditor() {}

    /** multipart 폼의 전송 개행만 정규화한다. 저장 후에는 승인 원문 바이트를 바꾸지 않는다. */
    static String canonicalInput(String text) {
        if (text == null) return null;
        String canonical = text.replace("\r\n", "\n");
        if (canonical.indexOf('\r') >= 0) throw invalid("단독 CR 개행은 사용할 수 없습니다.");
        return canonical;
    }

    static String sha256(String text) {
        try { return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(text.getBytes(StandardCharsets.UTF_8))); }
        catch (java.security.NoSuchAlgorithmException impossible) { throw new IllegalStateException(impossible); }
    }

    static void validate(String text, NginxChangeRequest request) {
        if (text == null || text.isBlank()) throw invalid("Nginx 설정 원문을 입력하세요.");
        try {
            var bytes = StandardCharsets.UTF_8.newEncoder().onMalformedInput(CodingErrorAction.REPORT)
                .onUnmappableCharacter(CodingErrorAction.REPORT).encode(CharBuffer.wrap(text));
            if (bytes.remaining() > MAX_BYTES) throw invalid("Nginx 설정 원문은 UTF-8 기준 60KB 이하여야 합니다.");
        } catch (java.nio.charset.CharacterCodingException ex) { throw invalid("Nginx 설정 원문의 문자 인코딩을 확인하세요."); }
        if (text.chars().anyMatch(c -> c < 32 && c != '\n' && c != '\t')
            || text.contains("-----BEGIN ") || text.contains("${")
            || java.util.regex.Pattern.compile("(?im)^\\s*#\\s*Generated by Deploy System").matcher(text).find())
            throw invalid("설정 본문에 제어 문자, 개인키 또는 관리 헤더를 넣을 수 없습니다.");
        String first = null;
        List<String> args = new ArrayList<>();
        int depth = 0, servers = 0;
        for (Token token : tokens(text)) {
            String value = token.value();
            if (!token.separator()) {
                if (first == null) { first = value; if (!DIRECTIVES.contains(first)) throw invalid("허용되지 않은 Nginx 지시어입니다: " + first); }
                else args.add(value);
                continue;
            }
            if ("}".equals(value)) {
                if (first != null || --depth < 0) throw invalid("Nginx 설정의 중괄호 또는 세미콜론을 확인하세요.");
            } else {
                if (first == null) throw invalid("Nginx 설정 지시어를 확인하세요.");
                if ("{".equals(value)) {
                    if (depth == 0 && first.equals("server")) servers++;
                    if (depth == 0 && !(first.equals("server") || first.equals("upstream")))
                        throw invalid("관리 설정은 upstream/server 블록만 포함할 수 있습니다.");
                    depth++;
                } else if (depth == 0) throw invalid("전체 nginx.conf 지시어는 편집할 수 없습니다.");
                validatePath(first, args, request);
                first = null; args = new ArrayList<>();
            }
        }
        if (depth != 0 || first != null || servers == 0) throw invalid("Nginx 설정의 server 블록, 닫는 중괄호 또는 세미콜론을 확인하세요.");
    }

    private static void validatePath(String directive, List<String> args, NginxChangeRequest request) {
        if (directive.equals("access_log") && !args.equals(List.of("off")))
            throw invalid("로그 경로를 직접 지정할 수 없습니다. access_log off만 사용할 수 있습니다.");
        if (directive.equals("root")) {
            String allowed = request.getWebRoot() == null ? "" : request.getWebRoot() + "/current";
            if (request.getPolicyType() == NginxPolicyType.REVERSE_PROXY || args.size() != 1 || !args.getFirst().equals(allowed)) throw invalid("정적 파일 경로는 이 정책의 배포 경로/current만 사용할 수 있습니다.");
        }
        if (directive.equals("ssl_certificate") || directive.equals("ssl_certificate_key")) {
            String file = directive.equals("ssl_certificate") ? "fullchain.pem" : "privkey.pem";
            if (!request.isTlsEnabled() || args.size() != 1 || !args.getFirst().equals("/etc/nginx/tls/" + request.getPolicyName() + "/current/" + file))
                throw invalid("인증서 경로는 이 정책의 관리 인증서만 사용할 수 있습니다.");
        }
    }

    private record Token(String value, boolean separator) {}
    private static List<Token> tokens(String text) {
        List<Token> result = new ArrayList<>(); StringBuilder word = new StringBuilder(); char quote = 0;
        boolean escape = false, comment = false, started = false;
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (comment) { if (c == '\n') comment = false; continue; }
            if (escape) {
                switch (c) {
                    case 't' -> word.append('\t'); case 'r' -> word.append('\r'); case 'n' -> word.append('\n');
                    case '\\', '\'', '"' -> word.append(c);
                    default -> word.append('\\').append(c);
                }
                started = true; escape = false; continue;
            }
            if (c == '\\') { escape = true; started = true; continue; }
            if (quote != 0) { if (c == quote) quote = 0; else word.append(c); continue; }
            if (c == '\'' || c == '"') { quote = c; started = true; continue; }
            if (c == '#') { if (started) { result.add(new Token(word.toString(), false)); word.setLength(0); started = false; } comment = true; continue; }
            if (Character.isWhitespace(c) || c == '{' || c == '}' || c == ';') {
                if (started) { result.add(new Token(word.toString(), false)); word.setLength(0); started = false; }
                if (c == '{' || c == '}' || c == ';') result.add(new Token(String.valueOf(c), true));
            } else { word.append(c); started = true; }
        }
        if (quote != 0 || escape) throw invalid("Nginx 설정의 따옴표 또는 이스케이프 문자를 확인하세요.");
        if (started) result.add(new Token(word.toString(), false));
        return result;
    }

    static String render(NginxChangeRequest r) {
        StringBuilder out = new StringBuilder();
        List<NginxUpstream> rows = r.getEffectiveUpstreams();
        boolean group = !rows.isEmpty() && ((r.getUpstreamSnapshots() != null && !r.getUpstreamSnapshots().isEmpty()) || rows.size() > 1);
        String upstream = "deploy_policy_" + r.getPolicyName().replaceAll("[^A-Za-z0-9]", "_");
        if (group) {
            out.append("upstream ").append(upstream).append(" {\n");
            for (var row : rows) out.append("    server ").append(address(row.getHost(), row.getPort())).append(" max_fails=").append(r.getUpstreamMaxFails()).append(" fail_timeout=").append(r.getUpstreamFailTimeoutSec()).append("s;\n");
            out.append("}\n");
        }
        if (r.isTlsEnabled() && r.isRedirectHttp() && r.getListenPort() != 80)
            out.append("server { listen 80; server_name ").append(r.getServerName()).append("; return 301 https://$host$request_uri; }\n");
        out.append("server {\n    listen ").append(r.getListenPort()).append(r.isTlsEnabled() ? " ssl" + (r.isHttp2Enabled() ? " http2" : "") : "").append(";\n");
        if (r.isTlsEnabled()) out.append("    ssl_certificate /etc/nginx/tls/").append(r.getPolicyName()).append("/current/fullchain.pem;\n    ssl_certificate_key /etc/nginx/tls/").append(r.getPolicyName()).append("/current/privkey.pem;\n    ssl_protocols ").append(r.getTlsProtocols()).append(";\n");
        out.append("    server_name ").append(r.getServerName()).append(";\n    set $deploy_request_host $http_host;\n    if ($deploy_request_host = \"\") { set $deploy_request_host $host; }\n    client_max_body_size ").append(r.getClientMaxBodyMb()).append("m;\n");
        if (r.isTlsEnabled() && r.isHstsEnabled()) out.append("    add_header Strict-Transport-Security \"max-age=31536000\" always;\n");
        if (r.isSecurityHeaders()) out.append("    add_header X-Content-Type-Options \"nosniff\" always;\n    add_header X-Frame-Options \"SAMEORIGIN\" always;\n    add_header Referrer-Policy \"same-origin\" always;\n");
        out.append("    location / {\n");
        if (r.getPolicyType() == NginxPolicyType.REVERSE_PROXY) proxy(out, r, group ? upstream : address(r.getUpstreamHost(), r.getUpstreamPort()), group, rows.size());
        else out.append("        root ").append(r.getWebRoot()).append("/current;\n        try_files $uri $uri/ ").append(r.getPolicyType() == NginxPolicyType.STATIC_SPA ? "/index.html" : "=404").append(";\n");
        cidrs(out, r); out.append("    }\n");
        if (r.isApiProxyEnabled()) { out.append("    location ^~ ").append(r.getApiPrefix()).append(" {\n"); proxy(out, r, group ? upstream : address(r.getApiUpstreamHost(), r.getApiUpstreamPort()), group, rows.size()); cidrs(out, r); out.append("    }\n"); }
        return out.append("}\n").toString();
    }

    private static void proxy(StringBuilder out, NginxChangeRequest r, String destination, boolean group, int count) {
        out.append("        proxy_pass http://").append(destination).append(";\n");
        if (group) out.append("        proxy_connect_timeout ").append(r.getProxyConnectTimeoutSec()).append("s;\n        proxy_next_upstream error timeout http_502 http_503 http_504;\n        proxy_next_upstream_tries ").append(count).append(";\n        proxy_next_upstream_timeout ").append(r.getProxyConnectTimeoutSec() * count).append("s;\n");
        out.append("        proxy_http_version 1.1;\n        proxy_set_header Host $deploy_request_host;\n        proxy_set_header X-Real-IP $remote_addr;\n        proxy_set_header X-Forwarded-For $remote_addr;\n        proxy_set_header X-Forwarded-Proto $scheme;\n        proxy_set_header X-Forwarded-Host $deploy_request_host;\n        proxy_set_header Forwarded \"\";\n        proxy_set_header X-Forwarded-Port \"\";\n        proxy_set_header X-Forwarded-Prefix \"\";\n        proxy_set_header X-Forwarded-Ssl \"\";\n");
        if (r.isWebsocketEnabled()) out.append("        proxy_set_header Upgrade $http_upgrade;\n        proxy_set_header Connection \"upgrade\";\n");
        out.append("        proxy_read_timeout ").append(r.getProxyReadTimeoutSec()).append("s;\n        proxy_send_timeout ").append(r.getProxySendTimeoutSec()).append("s;\n        proxy_buffering ").append(r.isProxyBuffering() ? "on" : "off").append(";\n");
    }
    private static String address(String host, int port) { return (host.contains(":") ? "[" + host + "]" : host) + ":" + port; }
    private static void cidrs(StringBuilder out, NginxChangeRequest r) {
        if (r.getAllowedCidrs() == null || r.getAllowedCidrs().isBlank()) return;
        for (String cidr : r.getAllowedCidrs().split(",")) out.append("        allow ").append(cidr).append(";\n");
        out.append("        deny all;\n");
    }
    private static ResponseStatusException invalid(String message) { return new ResponseStatusException(HttpStatus.BAD_REQUEST, message); }
}
