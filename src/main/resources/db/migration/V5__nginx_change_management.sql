CREATE TABLE nginx_change_request (
  id BIGINT NOT NULL AUTO_INCREMENT,
  server_id BIGINT NOT NULL,
  requested_by_id BIGINT NOT NULL,
  approved_by_id BIGINT NULL,
  rollback_of_id BIGINT NULL,
  status VARCHAR(24) NOT NULL,
  policy_name VARCHAR(80) NOT NULL,
  server_name VARCHAR(255) NOT NULL,
  listen_port INT NOT NULL,
  upstream_host VARCHAR(255) NOT NULL,
  upstream_port INT NOT NULL,
  websocket_enabled BIT(1) NOT NULL DEFAULT b'0',
  tls_enabled BIT(1) NOT NULL DEFAULT b'0',
  tls_protocols VARCHAR(40) NOT NULL DEFAULT 'TLSv1.2 TLSv1.3',
  http2_enabled BIT(1) NOT NULL DEFAULT b'1',
  redirect_http BIT(1) NOT NULL DEFAULT b'1',
  hsts_enabled BIT(1) NOT NULL DEFAULT b'1',
  client_max_body_mb INT NOT NULL DEFAULT 50,
  proxy_read_timeout_sec INT NOT NULL DEFAULT 300,
  proxy_send_timeout_sec INT NOT NULL DEFAULT 300,
  proxy_buffering BIT(1) NOT NULL DEFAULT b'1',
  security_headers BIT(1) NOT NULL DEFAULT b'1',
  allowed_cidrs VARCHAR(1000) NULL,
  certificate_name VARCHAR(120) NULL,
  certificate_file_name VARCHAR(255) NULL,
  private_key_file_name VARCHAR(255) NULL,
  storage_key VARCHAR(64) NULL,
  backup_path VARCHAR(1000) NULL,
  error_message VARCHAR(2000) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  approved_at DATETIME(6) NULL,
  applied_at DATETIME(6) NULL,
  PRIMARY KEY (id),
  KEY idx_nginx_change_status_created (status, created_at),
  KEY idx_nginx_change_server_created (server_id, created_at),
  CONSTRAINT fk_nginx_change_server FOREIGN KEY (server_id) REFERENCES server (id),
  CONSTRAINT fk_nginx_change_requester FOREIGN KEY (requested_by_id) REFERENCES users (id),
  CONSTRAINT fk_nginx_change_approver FOREIGN KEY (approved_by_id) REFERENCES users (id),
  CONSTRAINT fk_nginx_change_rollback FOREIGN KEY (rollback_of_id) REFERENCES nginx_change_request (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
