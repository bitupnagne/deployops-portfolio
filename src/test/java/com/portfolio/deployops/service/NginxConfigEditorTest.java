package com.portfolio.deployops.service;

import static org.assertj.core.api.Assertions.*;
import com.portfolio.deployops.domain.*;
import java.util.List;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

class NginxConfigEditorTest {
    static NginxChangeRequest request() {
        return NginxChangeRequest.builder().id(7L).policyName("portal-main")
            .policyType(NginxPolicyType.REVERSE_PROXY).serverName("portal.local").listenPort(8080)
            .upstreamHost("198.18.8.2").upstreamPort(8081).tlsProtocols("TLSv1.2 TLSv1.3")
            .clientMaxBodyMb(50).proxyReadTimeoutSec(300).proxySendTimeoutSec(300)
            .requestedBy(User.builder().id(10L).build()).status(NginxChangeStatus.PENDING).build();
    }
    @Test void deterministicPreviewUsesStableUpstreamAndPreservesOrderedRegisteredServers() {
        var r=request(); r.setUpstreamSnapshots(List.of(new NginxUpstream("PROXY",0,2L,"198.18.8.3",9000),new NginxUpstream("PROXY",1,3L,"198.18.8.2",9001)));
        String text=NginxConfigEditor.render(r);
        assertThat(text).contains("upstream deploy_policy_portal_main {", "proxy_pass http://deploy_policy_portal_main;")
            .containsSubsequence("server 198.18.8.3:9000", "server 198.18.8.2:9001");
        r.setId(999L); assertThat(NginxConfigEditor.render(r)).isEqualTo(text);
        assertThatCode(()->NginxConfigEditor.validate(text,r)).doesNotThrowAnyException();
    }
    @Test void tlsStaticApiPreviewUsesOnlyManagedRootsAndProtectedForwardingHeaders() {
        var r=request(); r.setPolicyType(NginxPolicyType.STATIC_SPA);r.setWebRoot("/var/www/portal");
        r.setTlsEnabled(true);r.setListenPort(443);r.setRedirectHttp(true);r.setHttp2Enabled(true);
        r.setApiProxyEnabled(true);r.setApiPrefix("/api/");r.setApiUpstreamHost("198.18.8.2");r.setApiUpstreamPort(8081);
        String text=NginxConfigEditor.render(r);
        assertThat(text).contains("root /var/www/portal/current;", "try_files $uri $uri/ /index.html;",
            "ssl_certificate /etc/nginx/tls/portal-main/current/fullchain.pem;", "location ^~ /api/", "proxy_set_header X-Forwarded-For $remote_addr;");
        assertThatCode(()->NginxConfigEditor.validate(text,r)).doesNotThrowAnyException();
    }
    @Test void canonicalizesOnlyTransportCrlfAndDoesNotTrimReviewedBody() {
        String raw=" # comment\r\nserver {\r\n listen 8080;\r\n}\r\n\r\n";
        assertThat(NginxConfigEditor.canonicalInput(raw)).isEqualTo(raw.replace("\r\n","\n"));
        assertThatThrownBy(()->NginxConfigEditor.canonicalInput("server {\r}" )).hasMessageContaining("CR");
        assertThat(NginxConfigEditor.sha256("a\n")).isNotEqualTo(NginxConfigEditor.sha256("a"));
    }
    @ParameterizedTest @ValueSource(strings={"include /etc/passwd;","load_module modules/x.so;","alias /etc;","error_log /tmp/error;","access_log /tmp/access;","root /var/www/other/current;","ssl_certificate /etc/passwd;","proxy_cache off;"})
    void rejectsArbitraryFileDirectivesAndUnsupportedOptions(String directive) {
        assertThatThrownBy(()->NginxConfigEditor.validate("server { "+directive+" }",request())).isInstanceOf(RuntimeException.class);
    }
    @ParameterizedTest @ValueSource(strings={"# comment only\n", "server { listen 8080 }", "server { listen 8080;", "server { set $x \"unterminated; }", " # Generated by Deploy System. Request 4.\nserver {}", "server { return 200 ${name}; }"})
    void rejectsMalformedOrManagedHeaderInput(String text) {
        assertThatThrownBy(()->NginxConfigEditor.validate(text,request())).isInstanceOf(RuntimeException.class);
    }
    @Test void utf8ByteLimitAndMalformedUnicodeAreCheckedBeforePersistence() {
        assertThatThrownBy(()->NginxConfigEditor.validate("# "+"한".repeat(21000)+"\nserver {}",request())).hasMessageContaining("60KB");
        assertThatThrownBy(()->NginxConfigEditor.validate("server { # \uD800\n}",request())).hasMessageContaining("인코딩");
        assertThatThrownBy(()->NginxConfigEditor.validate("server {\r\n}",request())).hasMessageContaining("제어 문자");
    }
    @Test void quotedStructuralCharactersAreNotParsedAsDirectives() {
        assertThatCode(()->NginxConfigEditor.validate("server { add_header X-Example \"a;{b}\"; access_log off; }",request())).doesNotThrowAnyException();
    }
}
