package com.portfolio.deployops.service;

import static org.assertj.core.api.Assertions.assertThat;

import com.portfolio.deployops.domain.BuildToolType;
import com.portfolio.deployops.domain.Project;
import java.util.Map;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * {@code .gitlab-ci.yml} 에서 프로젝트 설정을 거꾸로 읽어 내는 규칙을 고정한다.
 *
 * <p>왜 테스트가 필요한가 — 실제 화면에서 제안이 비어 있을 때 그것이
 * "이미 같은 값이라 제안할 게 없다" 인지 "파서가 아무것도 못 읽었다" 인지
 * 구분할 방법이 없다. 둘은 완전히 다른 상황인데 화면에는 똑같이 보인다.
 *
 * <p>아래 문자열은 예제 WorkHub 저장소의 CI 구성을 표현한다.
 */
class GitlabCiInspectServiceTest {

    private final GitlabCiInspectService service = new GitlabCiInspectService();

    /** 예제 저장소의 .gitlab-ci.yml (배포시스템이 만들어 준 형태). */
    private static final String EXAMPLE_CI = """
        # Generated by Deploy System. Review and merge through Deploy System.
        stages:
          - build
          - image

        variables:
          IMAGE_REPOSITORY: "192.0.2.96:5000/worksystem/worksystem-server"
          IMAGE_TAG: "${CI_COMMIT_REF_SLUG}-${CI_COMMIT_SHORT_SHA}-${CI_PIPELINE_ID}"
          DOCKERFILE_PATH: "Dockerfile"
          DOCKER_CONTEXT_PATH: "."

        build_and_push_image:
          stage: image
          script:
            - docker build -f "$DOCKERFILE_PATH" -t "$IMAGE_REPOSITORY:$IMAGE_TAG" "$DOCKER_CONTEXT_PATH"
            - docker push "$IMAGE_REPOSITORY:$IMAGE_TAG"
        """;

    private Project empty() {
        return Project.builder().id(1L).name("worksystem-server").build();
    }

    @Test
    @DisplayName("variables 블록에서 이미지 저장소와 경로를 읽는다")
    void readsValuesFromVariablesBlock() {
        Map<String, String> found = service.suggest(EXAMPLE_CI, empty());

        assertThat(found).containsEntry("imageRepository", "192.0.2.96:5000/worksystem/worksystem-server");
        assertThat(found).containsEntry("dockerfilePath", "Dockerfile");
        assertThat(found).containsEntry("dockerContextPath", ".");
    }

    @Test
    @DisplayName("이미 같은 값이면 제안하지 않는다")
    void alreadyMatchingValuesAreNotSuggested() {
        Project project = empty();
        project.setImageRepository("192.0.2.96:5000/worksystem/worksystem-server");
        project.setDockerfilePath("Dockerfile");
        project.setDockerContextPath(".");

        // 화면에서 제안 목록이 비는 정상적인 경우다 — 고칠 것이 없다는 뜻이지 파서 실패가 아니다.
        assertThat(service.suggest(EXAMPLE_CI, project)).isEmpty();
    }

    @Test
    @DisplayName("변수를 안 쓰는 CI 파일은 명령줄에서 직접 읽는다")
    void readsValuesFromPlainCommands() {
        String yaml = """
            build:
              script:
                - ./mvnw -B clean package -DskipTests
                - docker build -f docker/Dockerfile.prod -t nexus.example.com:18443/pay/api:1.2.3 .
                - docker push nexus.example.com:18443/pay/api:1.2.3
              artifacts:
                expire_in: 1 day
                paths:
                  - target/app.jar
            """;

        Map<String, String> found = service.suggest(yaml, empty());

        assertThat(found).containsEntry("imageRepository", "nexus.example.com:18443/pay/api");
        assertThat(found).containsEntry("dockerfilePath", "docker/Dockerfile.prod");
        assertThat(found).containsEntry("artifactPath", "target/app.jar");
        assertThat(found).containsEntry("buildTool", BuildToolType.MAVEN.name());
    }

    /**
     * {@code $IMAGE_REPOSITORY} 같은 변수 참조를 값으로 착각하면 안 된다.
     *
     * <p>이런 값이 조용히 설정에 들어가면 배포가 존재하지 않는 이미지를 집는데,
     * 화면에는 그럴듯한 글자가 적혀 있어 아무도 그것을 의심하지 않는다.
     */
    @Test
    @DisplayName("변수 참조는 값으로 제안하지 않는다")
    void variableReferencesAreNotSuggested() {
        String yaml = """
            build:
              script:
                - docker build -f "$DOCKERFILE_PATH" -t "$IMAGE_REPOSITORY:$TAG" .
                - docker push "${IMAGE_REPOSITORY}:${TAG}"
            """;

        assertThat(service.suggest(yaml, empty()))
            .doesNotContainKeys("imageRepository", "dockerfilePath");
    }

    @Test
    @DisplayName("빈 파일이면 아무것도 제안하지 않는다")
    void emptyContentYieldsNothing() {
        assertThat(service.suggest(null, empty())).isEmpty();
        assertThat(service.suggest("   ", empty())).isEmpty();
    }
}
