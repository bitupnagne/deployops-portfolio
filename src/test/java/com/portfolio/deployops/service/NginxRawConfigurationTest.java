package com.portfolio.deployops.service;

import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;
import static org.mockito.ArgumentMatchers.*;
import com.portfolio.deployops.domain.*;
import com.portfolio.deployops.dto.NginxPolicyForm;
import com.portfolio.deployops.repository.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import java.util.concurrent.atomic.AtomicReference;
import org.junit.jupiter.api.*;
import org.springframework.test.util.ReflectionTestUtils;

class NginxRawConfigurationTest {
    final NginxChangeRequestRepository repo=mock(NginxChangeRequestRepository.class);
    final ServerRepository servers=mock(ServerRepository.class);
    final SshCommandService ssh=mock(SshCommandService.class);
    final ExecutionGuardRepository guard=mock(ExecutionGuardRepository.class);
    final NginxChangeService service=new NginxChangeService(repo,servers,ssh,guard);
    final Server web=Server.builder().id(1L).name("web01").serverType(ServerType.WEB).controlMode(ServerControlMode.AGENT).agentBindingId("web-registration-1").build();
    final String body="# reviewed comment\nserver {\n    listen 8080;\n}\n";
    @BeforeEach void setup(){
        when(servers.findById(1L)).thenReturn(Optional.of(web));when(guard.lockSingleton()).thenReturn(1);
        ReflectionTestUtils.setField(service,"uploadDir",System.getProperty("java.io.tmpdir")+"/nginx-raw-test");
    }
    NginxPolicyForm form(){var f=new NginxPolicyForm();f.setServerId(1L);f.setPolicyName("portal-main");f.setServerName("portal.local");f.setListenPort(8080);f.setUpstreamHost("198.18.8.2");return f;}
    NginxChangeRequest request(){var r=NginxConfigEditorTest.request();r.setServer(web);r.setRequestedControlMode(web.getControlMode());r.setRequestedAgentBindingId(web.getAgentBindingId());r.setRawConfig(body);r.setRawConfigSha256(NginxConfigEditor.sha256(body));return r;}
    @Test void multipartCrlfIsCanonicalizedOnceAndFrozenWithServerDigest(){
        var f=form();f.setRawConfig(body.replace("\n","\r\n"));var saved=service.create(f,null,null,10L);
        assertThat(saved.getRawConfig()).isEqualTo(body);assertThat(saved.getRawConfigSha256()).isEqualTo(NginxConfigEditor.sha256(body));
        verify(repo).insert(saved);verifyNoInteractions(ssh);
    }
    @Test void omittedRawFieldKeepsLegacyTypedRequestAndPreviewHasNoMutation(){
        var saved=service.create(form(),null,null,10L);assertThat(saved.getRawConfig()).isNull();
        clearInvocations(repo);var preview=service.preview(form());assertThat(preview.config()).contains("proxy_pass http://198.18.8.2:8080;");
        assertThat(preview.sha256()).isEqualTo(NginxConfigEditor.sha256(preview.config()));verifyNoInteractions(repo,ssh);
    }
    @Test void rejectedRawCannotCreateRequestOrReachRemote(){
        var f=form();f.setRawConfig("server { include /etc/passwd; }");
        assertThatThrownBy(()->service.create(f,null,null,10L)).hasMessageContaining("허용되지 않은");verifyNoInteractions(repo,ssh);
    }
    @Test void explicitlyEmptyEditedBodyCannotFallBackToTypedApplication(){
        for(String empty:List.of("","  ","\r\n\t")) {
            var f=form();f.setRawConfig(empty);assertThatThrownBy(()->service.create(f,null,null,10L)).hasMessageContaining("원문을 입력");
        }
        verifyNoInteractions(repo,ssh);
    }
    @Test void requestedBodyIsReadOnlyAndTamperingIsRejected(){
        var r=request();when(repo.findById(7L)).thenReturn(Optional.of(r));
        var config=service.requestedConfiguration(7L);assertThat(config.config()).isEqualTo(body);assertThat(config.editable()).isFalse();assertThat(config.legacyTyped()).isFalse();
        r.setRawConfig(body+"\n");assertThatThrownBy(()->service.requestedConfiguration(7L)).hasMessageContaining("검증 값");verifyNoInteractions(ssh);
    }
    @Test void currentManagedBodyIsDecodedExactlyWithoutManagementHeader(){
        String encoded=Base64.getEncoder().encodeToString(body.getBytes(StandardCharsets.UTF_8));
        when(ssh.execute(eq(web),any())).thenReturn(NginxRollbackSnapshotTest.result("EDITOR_CONFIG_VERSION=1\n"),NginxRollbackSnapshotTest.result("CURRENT_CONFIG_PRESENT=true\nCURRENT_REQUEST_ID=7\nCONFIG_BODY_BASE64="+encoded+"\nCONFIG_BODY_SHA="+NginxConfigEditor.sha256(body)+"\nCURRENT_CONFIG_SHA="+NginxConfigEditor.sha256("# Generated by Deploy System. Request 7.\n"+body)+"\n"));
        var current=service.currentConfiguration(1L,"portal-main");assertThat(current.config()).isEqualTo(body);assertThat(current.editable()).isTrue();
        verify(ssh).execute(web,List.of("sudo","-n",NginxChangeService.AGENT,"read-config","--policy-name","portal-main"));
    }
    private void stubCurrentBody() {
        String encoded=Base64.getEncoder().encodeToString(body.getBytes(StandardCharsets.UTF_8));
        when(ssh.execute(eq(web),any())).thenReturn(NginxRollbackSnapshotTest.result("EDITOR_CONFIG_VERSION=1\n"),
            NginxRollbackSnapshotTest.result("CURRENT_CONFIG_PRESENT=true\nCURRENT_REQUEST_ID=7\nCONFIG_BODY_BASE64="+encoded
                +"\nCONFIG_BODY_SHA="+NginxConfigEditor.sha256(body)+"\nCURRENT_CONFIG_SHA="
                +NginxConfigEditor.sha256("# Generated by Deploy System. Request 7.\n"+body)+"\n"));
    }
    private NginxChangeRequest currentMetadata() {
        var r=request();r.setPolicyName("portal-main");r.setStatus(NginxChangeStatus.APPLIED);
        r.setNativeRequestId(7L);r.setAppliedConfigHash(NginxConfigEditor.sha256("# Generated by Deploy System. Request 7.\n"+body));
        r.setPolicyType(NginxPolicyType.STATIC_SPA);r.setServerName("multi.qa.local");r.setListenPort(18093);
        r.setTlsEnabled(false);r.setWebRoot("/var/www/qa-multi-c/current");r.setApiProxyEnabled(true);
        r.setApiPrefix("/api/");r.setApiUpstreamHost("198.18.31.100");r.setApiUpstreamPort(18203);
        r.setUpstreamSnapshots(List.of());when(repo.findLatestCompletedId(1L,"portal-main")).thenReturn(14L);
        when(repo.findById(14L)).thenReturn(Optional.of(r));return r;
    }
    @Test void currentEditMetadataMatchesNativeGenerationAndResolvesUniqueCurrentVipWithoutExposingStorage() {
        var r=currentMetadata();var vip=mock(WasVipNginxResolver.class);service.setWasVipResolver(vip);
        when(vip.choices(web)).thenReturn(List.of(new WasVipNginxResolver.Choice(3L,"C",2L,"PROD","198.18.31.100",18203)));
        stubCurrentBody();var settings=service.currentConfiguration(1L,"portal-main").editorSettings();
        assertThat(settings).containsEntry("policyType","STATIC_SPA").containsEntry("serverName","multi.qa.local")
            .containsEntry("listenPort",18093).containsEntry("tlsEnabled",false).containsEntry("wasVipSelection","3:2")
            .containsEntry("upstreamsResolved",true).doesNotContainKeys("storageKey","privateKeyFileName","rawConfig");
        r.setStatus(NginxChangeStatus.ROLLED_BACK);stubCurrentBody();
        assertThat(service.currentConfiguration(1L,"portal-main").editorSettings()).isNotNull();
    }
    @Test void mismatchedCompletedMetadataNeverHydratesAnotherServerPolicyOrGeneration() {
        for(String mismatch:List.of("server","policy","status","native","full","body","storedHash")) {
            var r=currentMetadata();
            switch(mismatch) {
                case "server" -> r.setServer(Server.builder().id(2L).build());
                case "policy" -> r.setPolicyName("other");
                case "status" -> r.setStatus(NginxChangeStatus.PENDING);
                case "native" -> r.setNativeRequestId(8L);
                case "full" -> r.setAppliedConfigHash("f".repeat(64));
                case "body" -> r.setRawConfig(body+"# changed");
                case "storedHash" -> r.setRawConfigSha256("f".repeat(64));
            }
            stubCurrentBody();var result=service.currentConfiguration(1L,"portal-main");
            assertThat(result.editorSettings()).as(mismatch).isNull();assertThat(result.config()).isEqualTo(body);
        }
    }
    @Test void directRegisteredUpstreamIdsAreRetainedAndUnknownLegacyAddressesRequireManualSelection() {
        var r=currentMetadata();r.setUpstreamSnapshots(List.of(new NginxUpstream("API",0,4L,"198.18.8.4",8080)));
        stubCurrentBody();assertThat(service.currentConfiguration(1L,"portal-main").editorSettings())
            .containsEntry("upstreams",List.of(Map.of("serverId",4L,"port",8080))).containsEntry("upstreamsResolved",true);
        r.setUpstreamSnapshots(List.of());stubCurrentBody();assertThat(service.currentConfiguration(1L,"portal-main").editorSettings())
            .containsEntry("upstreamsResolved",false).containsEntry("wasVipSelection","");
    }
    @Test void currentBodyRequiresMatchingManagedGenerationAndFullFileDigest(){
        String encoded=Base64.getEncoder().encodeToString(body.getBytes(StandardCharsets.UTF_8));
        for(String id:List.of("7","absent","0","007")) {
            when(ssh.execute(eq(web),any())).thenReturn(NginxRollbackSnapshotTest.result("EDITOR_CONFIG_VERSION=1\n"),NginxRollbackSnapshotTest.result("CURRENT_CONFIG_PRESENT=true\nCURRENT_REQUEST_ID="+id+"\nCONFIG_BODY_BASE64="+encoded+"\nCONFIG_BODY_SHA="+NginxConfigEditor.sha256(body)+"\nCURRENT_CONFIG_SHA="+"f".repeat(64)+"\n"));
            assertThatThrownBy(()->service.currentConfiguration(1L,"portal-main")).hasMessageContaining("세대 또는 검증");
        }
    }
    @Test void currentManagedBodyRejectsHashMismatchAndOldAgent(){
        when(ssh.execute(eq(web),any())).thenReturn(NginxRollbackSnapshotTest.result("EDITOR_CONFIG_VERSION=0\n"));
        assertThatThrownBy(()->service.currentConfiguration(1L,"portal-main")).hasMessageContaining("최신 설치기");
        when(ssh.execute(eq(web),any())).thenReturn(NginxRollbackSnapshotTest.result("EDITOR_CONFIG_VERSION=1\n"),NginxRollbackSnapshotTest.result("CURRENT_CONFIG_PRESENT=true\nCONFIG_BODY_BASE64=eA==\nCONFIG_BODY_SHA="+"a".repeat(64)+"\n"));
        assertThatThrownBy(()->service.currentConfiguration(1L,"portal-main")).hasMessageContaining("검증 값");
    }
    @Test void approvedBodyIsUploadedExactlyAndBothDigestsGateSuccessfulNativeProof() throws Exception {
        var r=request();when(repo.findById(7L)).thenReturn(Optional.of(r));when(repo.acquireApproval(7L,20L)).thenReturn(1);when(repo.storeNativeProof(any(),any(),any(),any(),any())).thenReturn(1);
        String full=NginxConfigEditor.sha256("# Generated by Deploy System. Request 7.\n"+body);
        AtomicReference<Path> uploaded=new AtomicReference<>();
        when(ssh.copyFile(eq(web),any(Path.class),anyString())).thenAnswer(call->{Path path=call.getArgument(1);uploaded.set(path);assertThat(Files.readString(path,StandardCharsets.UTF_8)).isEqualTo(body);return NginxRollbackSnapshotTest.result("");});
        when(ssh.execute(eq(web),any())).thenAnswer(call->{List<String> args=call.getArgument(1);if(args.contains("inspect"))return NginxRollbackSnapshotTest.result("EDITOR_CONFIG_VERSION=1\n");if(args.contains("apply")){assertThat(args).containsSubsequence("--config-file","/var/tmp/deploy-ops/nginx-change-7/policy.conf","--config-sha256",r.getRawConfigSha256());return NginxRollbackSnapshotTest.result("BACKUP_PATH=/var/backups/deploy-system/nginx/raw7\nBACKUP_SNAPSHOT_SHA="+NginxRollbackSnapshotTest.A+"\nCONFIG_BODY_SHA="+r.getRawConfigSha256()+"\n"+NginxRollbackSnapshotTest.proof("CURRENT_",NginxRollbackSnapshotTest.B,full,"7"));}return NginxRollbackSnapshotTest.result("");});
        service.approveAndApply(7L,20L);
        assertThat(Files.exists(uploaded.get())).isFalse();verify(ssh).execute(web,List.of("rm","-rf","--","/var/tmp/deploy-ops/nginx-change-7"));
        verify(repo).storeNativeProof(7L,NginxRollbackSnapshotTest.A,NginxRollbackSnapshotTest.B,full,7L);
    }
    @Test void changedApprovedBodyIsRejectedBeforeAnyRemoteOperation(){
        var r=request();r.setRawConfigSha256("f".repeat(64));when(repo.findById(7L)).thenReturn(Optional.of(r));when(repo.acquireApproval(7L,20L)).thenReturn(1);
        assertThatThrownBy(()->service.approveAndApply(7L,20L)).hasMessageContaining("검증 값");verifyNoInteractions(ssh);verify(repo,never()).storeNativeProof(any(),any(),any(),any(),any());
    }
    @org.junit.jupiter.params.ParameterizedTest
    @org.junit.jupiter.params.provider.ValueSource(booleans={true,false})
    void successfulCommandWithEitherWrongBodyOrFullFileDigestIsFailedAndNeverRecordsProof(boolean wrongBody){
        var r=request();when(repo.findById(7L)).thenReturn(Optional.of(r));when(repo.acquireApproval(7L,20L)).thenReturn(1);
        when(ssh.copyFile(eq(web),any(Path.class),anyString())).thenReturn(NginxRollbackSnapshotTest.result(""));
        when(ssh.execute(eq(web),any())).thenAnswer(call->{List<String> args=call.getArgument(1);return NginxRollbackSnapshotTest.result(args.contains("inspect")?"EDITOR_CONFIG_VERSION=1\n":args.contains("apply")?"BACKUP_PATH=/var/backups/deploy-system/nginx/raw7\nBACKUP_SNAPSHOT_SHA="+NginxRollbackSnapshotTest.A+"\nCONFIG_BODY_SHA="+(wrongBody?"f".repeat(64):r.getRawConfigSha256())+"\n"+NginxRollbackSnapshotTest.proof("CURRENT_",NginxRollbackSnapshotTest.B,wrongBody?NginxConfigEditor.sha256("# Generated by Deploy System. Request 7.\n"+body):"f".repeat(64),"7"):"");});
        assertThatThrownBy(()->service.approveAndApply(7L,20L)).hasMessageContaining("승인한 원문");verify(repo,never()).storeNativeProof(any(),any(),any(),any(),any());verify(repo).finish(eq(7L),eq(NginxChangeStatus.FAILED),any(),any());
    }
}
